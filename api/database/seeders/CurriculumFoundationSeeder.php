            $module = Module::where('slug', $slug)->first();
            if (!$module) {
                continue;
            }

            // Find associated simulation (if any)
            $sim = $module->simulations()->first();
            $simId = $sim ? $sim->id : null;

            $primarySet = false;

            foreach ($alignmentList as $item) {
                $isPrimary = $item['is_primary'] ?? false;

                CurriculumAlignment::updateOrCreate(
                    [
                        'module_id' => $module->id,
                        'education_level' => $item['education_level'],
                        'curriculum_phase' => $item['curriculum_phase'],
                        'grade_level' => $item['grade_level'],
