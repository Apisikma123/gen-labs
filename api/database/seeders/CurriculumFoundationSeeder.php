                        'official_source_url' => $item['official_source_url'] ?? null,
                        'verification_status' => $item['verification_status'] ?? 'unverified',
                        'verification_notes' => $item['verification_notes'] ?? null,
                        'is_primary' => $isPrimary,
                    ]
                );

                $totalAlignments++;

                // If primary, update the convenience columns on the module row itself
                if ($isPrimary && !$primarySet) {
                    $module->update([
                        'education_level' => $item['education_level'],
                        'grade_level' => $item['grade_level'],
                        'curriculum_phase' => $item['curriculum_phase'],
                        'subject_name' => $item['subject_or_course'],
                        'curriculum_source' => $item['official_source_code'] . ' - ' . $item['official_source_title'],
                        'verification_status' => $item['verification_status'],
                    ]);
                    $primarySet = true;
                }
            }

            $totalMapped++;
        }

        $this->command->info("Curriculum Foundation Seeding Completed: {$totalMapped} modules mapped into {$totalAlignments} curriculum alignment records.");
