const seenTitles = new Set<string>();
export const GENLAB_CATALOG_ITEMS: SimulationCatalogItem[] = Object.entries(GENLAB_SIMULATIONS)
  .filter(([slug, def]) => {
    const normTitle = (def.spec?.title || slug).trim().toLowerCase();
    if (seenTitles.has(normTitle)) return false;
    seenTitles.add(normTitle);
    return true;
  })
  .map(([slug, def]) => {
  const disciplineName = def.discipline || (def.spec?.domain ? String(def.spec.domain) : 'Teknologi Rekayasa Perangkat Lunak');
  const disciplineSlug = 
    disciplineName.includes('Perangkat Lunak') || disciplineName.includes('Computer') ? 'trpl' :
    disciplineName.includes('Akuntansi') ? 'akuntansi' :
    disciplineName.includes('Pemasaran') ? 'pemasaran' :
    disciplineName.includes('Hortikultura') ? 'agribisnis' : 'event';

  return {
    id: `genlab:${slug}`,
    slug,
    title: def.spec.title,
    discipline: disciplineName,
    disciplineSlug,
    category: def.category || 'Konsep Dasar',

    description: def.spec.description,
    difficulty: 'Menengah',
    status: 'active',
    engine: def.spec.engine,
    formula: def.formulaLatex || 'R = f(P_1, P_2, ...)',
    tags: def.spec.concepts || [slug],
    learningObjectives: (def.experiments?.map(e => e.objective).filter((o): o is string => Boolean(o)) || [
      'Memahami hubungan sebab-akibat parameter simulasi',
    ]),
    parametersPreview: Object.entries(def.spec.parameters || {}).map(([name, p]) => ({

      name: p.label || name,
      range: `${p.min} s.d. ${p.max} ${p.unit || ''}`.trim(),
    })),
    readoutsPreview: ['Hasil Perhitungan Langsung', 'Evaluasi Target Eksperimen'],
  };
});



